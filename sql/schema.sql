-- 1. Criação do Schema
CREATE SCHEMA IF NOT EXISTS "controle-social-jovens";

-- 2. Permissões para roles do Supabase (PostgREST / API)
GRANT USAGE ON SCHEMA "controle-social-jovens" TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA "controle-social-jovens"
    GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA "controle-social-jovens"
    GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA "controle-social-jovens"
    GRANT ALL ON FUNCTIONS TO anon, authenticated, service_role;

-- ============================================================================
-- 3. TABELAS
-- ============================================================================

-- 3.1. Tabela de Categorias (categories)
CREATE TABLE IF NOT EXISTS "controle-social-jovens".categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3.2. Tabela de Produtos (products)
-- Nota: stock_quantity pode ser NULL para produtos feitos na hora / sem controle de estoque
CREATE TABLE IF NOT EXISTS "controle-social-jovens".products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    category_id BIGINT NOT NULL REFERENCES "controle-social-jovens".categories(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    cost_price NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (cost_price >= 0),
    stock_quantity INTEGER NULL CHECK (stock_quantity IS NULL OR stock_quantity >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Caso a tabela products já exista sem a coluna cost_price:
ALTER TABLE "controle-social-jovens".products
    ADD COLUMN IF NOT EXISTS cost_price NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (cost_price >= 0);

-- 3.2.1. Tabela de Eventos / Dias de Social (events)
CREATE TABLE IF NOT EXISTS "controle-social-jovens".events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    event_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'agendado' CHECK (status IN ('agendado', 'aberto', 'encerrado')),
    attendance_count INTEGER NOT NULL DEFAULT 0 CHECK (attendance_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3.3. Tabela de Pedidos (orders)
CREATE TABLE IF NOT EXISTS "controle-social-jovens".orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NULL REFERENCES "controle-social-jovens".events(id) ON DELETE SET NULL ON UPDATE CASCADE,
    customer_name VARCHAR(150) NOT NULL,
    payment_method VARCHAR(50) NOT NULL,
    payment_status VARCHAR(20) NOT NULL CHECK (payment_status IN ('pago', 'pendente')),
    total_amount NUMERIC(10, 2) NOT NULL CHECK (total_amount >= 0),
    paid_amount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    created_by_name VARCHAR(100) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    paid_at TIMESTAMPTZ NULL
);

-- Caso a tabela orders já exista sem as colunas event_id, paid_amount ou created_by_name:
ALTER TABLE "controle-social-jovens".orders
    ADD COLUMN IF NOT EXISTS event_id BIGINT NULL REFERENCES "controle-social-jovens".events(id) ON DELETE SET NULL ON UPDATE CASCADE;
ALTER TABLE "controle-social-jovens".orders
    ADD COLUMN IF NOT EXISTS paid_amount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0);
ALTER TABLE "controle-social-jovens".orders
    ADD COLUMN IF NOT EXISTS created_by_name VARCHAR(100) NULL;

-- 3.4. Tabela de Itens do Pedido (order_items)
CREATE TABLE IF NOT EXISTS "controle-social-jovens".order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES "controle-social-jovens".orders(id) ON DELETE CASCADE ON UPDATE CASCADE,
    product_id BIGINT NOT NULL REFERENCES "controle-social-jovens".products(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0)
);

-- 3.5. Tabela de Despesas Extras do Evento (event_expenses)
CREATE TABLE IF NOT EXISTS "controle-social-jovens".event_expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES "controle-social-jovens".events(id) ON DELETE CASCADE ON UPDATE CASCADE,
    description VARCHAR(150) NOT NULL,
    amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3.6. Tabela de Usuários / Operadores (app_users)
CREATE TABLE IF NOT EXISTS "controle-social-jovens".app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    pin VARCHAR(60) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'manager', 'seller')),
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

