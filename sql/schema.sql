-- ============================================================================
-- 5. FUNÇÃO RPC TRANSACIONAL (Opcional para chamada via supabase.rpc)
-- ============================================================================
CREATE OR REPLACE FUNCTION "controle-social-jovens".create_order_with_items(
    p_customer_name VARCHAR,
    p_payment_method VARCHAR,
    p_payment_status VARCHAR,
    p_items JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_order_id BIGINT;
    v_total_amount NUMERIC(10, 2) := 0;
    v_item JSONB;
    v_product RECORD;
    v_quantity INTEGER;
BEGIN
    IF p_payment_status NOT IN ('pago', 'pendente') THEN
        RAISE EXCEPTION 'Status de pagamento inválido: %. Use pago ou pendente.', p_payment_status;
    END IF;

    IF jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'O pedido deve conter pelo menos um item.';
    END IF;

    -- 1. Validar estoque e calcular valor total
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_quantity := (v_item->>'quantity')::INTEGER;
        IF v_quantity IS NULL OR v_quantity <= 0 THEN
            RAISE EXCEPTION 'Quantidade inválida para o produto ID %', v_item->>'product_id';
        END IF;

        SELECT * INTO v_product
        FROM "controle-social-jovens".products
        WHERE id = (v_item->>'product_id')::BIGINT
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Produto ID % não encontrado.', v_item->>'product_id';
        END IF;

        IF v_product.stock_quantity IS NOT NULL AND v_product.stock_quantity < v_quantity THEN
            RAISE EXCEPTION 'Estoque insuficiente para o produto "%" (Disponível: %, Solicitado: %)',
                v_product.name, v_product.stock_quantity, v_quantity;
        END IF;

        v_total_amount := v_total_amount + (v_product.price * v_quantity);
    END LOOP;

    -- 2. Inserir cabeçalho do pedido
    INSERT INTO "controle-social-jovens".orders (
        customer_name,
        payment_method,
        payment_status,
        total_amount,
        paid_at
    ) VALUES (
        p_customer_name,
        p_payment_method,
        p_payment_status,
        v_total_amount,
        CASE WHEN p_payment_status = 'pago' THEN NOW() ELSE NULL END
    )
    RETURNING id INTO v_order_id;

    -- 3. Inserir itens e abater estoque quando aplicável
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_quantity := (v_item->>'quantity')::INTEGER;

        SELECT * INTO v_product
        FROM "controle-social-jovens".products
        WHERE id = (v_item->>'product_id')::BIGINT;

        INSERT INTO "controle-social-jovens".order_items (
            order_id,
            product_id,
            quantity,
            unit_price
        ) VALUES (
            v_order_id,
            v_product.id,
            v_quantity,
            v_product.price
        );

        -- Abater estoque somente se stock_quantity não for nulo
        IF v_product.stock_quantity IS NOT NULL THEN
            UPDATE "controle-social-jovens".products
            SET stock_quantity = stock_quantity - v_quantity
            WHERE id = v_product.id;
        END IF;
    END LOOP;

    RETURN jsonb_build_object(
        'order_id', v_order_id,
        'total_amount', v_total_amount,
        'payment_status', p_payment_status
    );
END;
$$;

